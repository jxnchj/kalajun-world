"""Prepare the locally cached Poly Haven Rock 07 for the shared runtime/contact shell.
No image edits or new downloads: original scan textures/UVs are retained.
Run tools/.bpy/bin/python tools/blender/v2_shore_rock.py.
"""
from pathlib import Path
import bpy,json,shutil
from mathutils import Vector
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'assets/src/polyhaven/rock_07/rock_07_1k.gltf'
OUT=ROOT/'assets/src/v2/shore';OUT.mkdir(parents=True,exist_ok=True)
PUBLIC=ROOT/'web/public/assets/v2/shore';PUBLIC.mkdir(parents=True,exist_ok=True)
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(SOURCE))
objs=[o for o in bpy.context.scene.objects if o.type=='MESH']
assert len(objs)==1
o=objs[0];bpy.context.view_layer.objects.active=o;o.select_set(True)
bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
# Collapse redundant scanned triangles while preserving the real silhouette and UV boundaries.
mod=o.modifiers.new('runtime_scan_shell','DECIMATE');mod.ratio=.085
bpy.ops.object.modifier_apply(modifier=mod.name)
m=o.data
lo=Vector([min(v.co[i] for v in m.vertices) for i in range(3)])
hi=Vector([max(v.co[i] for v in m.vertices) for i in range(3)])
centre=(lo+hi)/2
horizontal=max((hi.x-lo.x)/2,(hi.y-lo.y)/2)
height=(hi.z-lo.z)/2
source_normals=[n.vector.copy() for n in m.corner_normals]
for v in m.vertices:v.co=Vector(((v.co.x-centre.x)/horizontal,(v.co.y-centre.y)/horizontal,(v.co.z-centre.z)/height))
# Direct coordinate edits must also transform imported custom split normals.
# The normalization scale is diag(1/horizontal,1/horizontal,1/height).
export_normals=[Vector((n.x*horizontal,n.y*horizontal,n.z*height)).normalized() for n in source_normals]
m.normals_split_custom_set(export_normals)
m.update();m.calc_loop_triangles()
# Exact same indexed shell is used for visible rocks and swept vegetation contact.
positions=[];normals=[];uv=[];indices=[];lookup={}
uvs=m.uv_layers.active.data
for tri in m.loop_triangles:
 for vi,li in zip(tri.vertices,tri.loops):
  p=m.vertices[vi].co;n=export_normals[li];t=uvs[li].uv
  key=tuple(round(v,6) for v in (p.x,p.z,-p.y,n.x,n.z,-n.y,t.x,1-t.y))
  if key not in lookup:
   lookup[key]=len(positions)//3;positions.extend(key[:3]);normals.extend(key[3:6]);uv.extend(key[6:])
  indices.append(lookup[key])
data={'position':positions,'normal':normals,'uv':uv,'index':indices}
js='// Generated by tools/blender/v2_shore_rock.py; Poly Haven Rock 07 (CC0).\nexport const shoreScan='+json.dumps(data,separators=(',',':'))+';\n'
(ROOT/'web/src/v2/shore-rock-data.js').write_text(js)
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'rock-07-shore.blend'))
for suffix in ['diff','nor_gl','arm']:shutil.copy2(SOURCE.parent/'textures'/('rock_07_'+suffix+'_1k.jpg'),PUBLIC/(suffix+'.jpg'))
meta={'name':'Poly Haven Rock 07','author':'Jenelle van Heerden','source':'https://polyhaven.com/a/rock_07','license':'CC0','licenseUrl':'https://polyhaven.com/license','sourceTriangles':14844,'runtimeTriangles':len(indices)//3,'vertices':len(positions)//3,'textureResolution':1024,'transform':'Blender Z-up to Three Y-up; original UVs, centered shell, unit top, isotropic horizontal scale','material':'Original scan diffuse, GL normal, packed AO/roughness; runtime muted tint/waterline','collision':'Runtime and vegetation collision use this identical shell'}
(PUBLIC/'sources.json').write_text(json.dumps(meta,indent=2)+'\n')
print(json.dumps(meta))

"""Bake the existing house_a transport with exactly nine runtime textile meshes.
Original sources and all original GI modules remain read-only. No new integrator.
"""
import argparse,base64,hashlib,json,math,time,shutil
from pathlib import Path
import bpy
import numpy as np
from v2_room_bounce import ROOT,definitions,geometry,bake as sky_bake
from v2_room_second_bounce import bake as second_bake
from v2_room_transport import bake as sun_bake
from v2_room_second_solar import bake as second_sun_bake
from v2_room_aperture_visibility import bake as aperture_bake
from v2_room_contact import geometry as contact_geometry,bake as contact_bake
SOURCE=ROOT/'assets/src/v2/pastoral/house_a-lived.blend'
GLB=ROOT/'web/public/assets/v2/house_a_lived.glb'
CLOTH=ROOT/'web/public/assets/v2/house-textiles62/geometry.glb'
MANIFEST=ROOT/'web/public/assets/v2/house-textiles62/manifest.json'
OUT=ROOT/'web/src/v2/house-textiles-gi73-data'
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
load=lambda p:json.loads(p.read_text().split('export default ',1)[1].rsplit(';',1)[0])
base=json.loads((ROOT/'web/src/v2/room-bounce-data.js').read_text().split('export const ROOM_BOUNCE_DATA = ',1)[1].rsplit(';',1)[0])['house_a']
manifest=json.loads(MANIFEST.read_text());assert sha(CLOTH)==manifest['geometrySHA256'] and sha(GLB)==manifest['sourceSHA256']
DERIVED={'kind':'house-textiles62','sourceSHA256':sha(GLB),'geometrySHA256':sha(CLOTH),'manifestSHA256':sha(MANIFEST),'nodes':[n['name']for n in manifest['nodes']]}
protected={str(p):sha(p)for p in [SOURCE,GLB,CLOTH,MANIFEST]}
def assemble(key):
 bpy.ops.wm.open_mainfile(filepath=str(SOURCE));originals={n:bpy.data.objects[n]for n in DERIVED['nodes']};before=set(bpy.data.objects)
 bpy.ops.import_scene.gltf(filepath=str(CLOTH));added=[o for o in bpy.data.objects if o not in before]
 for name,old in originals.items():
  matches=[o for o in added if o.type=='MESH'and(o.name==name or o.name.startswith(name+'.'))];assert len(matches)==1,(name,[o.name for o in matches])
  new=matches[0];mesh=new.data.copy();mesh.transform(old.matrix_world.inverted()@new.matrix_world);mesh.materials.clear()
  for m in old.data.materials:mesh.materials.append(m)
  old.data=mesh
 for o in added:bpy.data.objects.remove(o,do_unlink=True)
 external=[]
 if key!='house_a':
  old=load(ROOT/'web/src/v2/household-room-data'/f'{key}.js');external=old['externalSources']
  style=old['householdStyle']
  for ext in external:
   p=ROOT/ext['sourceBlend'];assert sha(p)==ext['blendSHA256'];prefix=f'household_{style}_'if'household-living'in str(p)else'entry_'
   with bpy.data.libraries.load(str(p),link=False)as(src,dst):dst.objects=[n for n in src.objects if n.startswith(prefix)]
   assert dst.objects
   for obj in dst.objects:
    bpy.context.scene.collection.objects.link(obj)
    if prefix.startswith('household_'):obj.location.x-=style*10
 bpy.context.view_layer.update();return external

def state(key,degree,external):
 definition=definitions()['house_a'];leaf=bpy.data.objects['house_a_door0'];initial=list(leaf.rotation_euler);leaf.rotation_euler[2]=-math.radians(degree) if initial[2]<0 else math.radians(degree);bpy.context.view_layer.update()
 d={**definition,'openings':[o for o in definition['openings']if o['kind']!='door']}if degree==0 else definition
 bvh,colors,_=geometry();first=sky_bake(key,d,bvh,colors,SOURCE,GLB,validity=base)
 # Preserve the original receiver grid/validity, exactly as existing door bakes.
 raw=np.frombuffer(base64.b64decode(first['data']),dtype='<f2').copy().reshape(4,-1,4);valid=np.frombuffer(base64.b64decode(base['data']),dtype='<f2').reshape(4,-1,4)[:,:,3]
 raw[:,:,3]=valid;raw[:,:,:3]*=(valid[:,:,None]>0);first['data']=base64.b64encode(raw.tobytes()).decode();first['validProbes']=base['validProbes'];first['openings']=base['openings']
 result={'sky':first,'secondSky':second_bake(key,d,first,bvh,colors,SOURCE,GLB),'solar':sun_bake(key,d,first,bvh,colors,SOURCE,GLB),'secondSolar':second_sun_bake(key,d,first,bvh,colors,SOURCE,GLB),'apertures':aperture_bake(key,first,bvh)}
 if degree==102:result['contact']=contact_bake(key,definition,SOURCE,GLB,contact_geometry())
 for f in result.values():
  f['derivedGeometry']=DERIVED
  if external:f['externalSources']=external;f['householdStyle']=0 if'entry'in key else int(key[-1])
 result.update({'key':key,'derivedGeometry':DERIVED,'doorPoses':[{'name':leaf.name,'openEuler':initial,'bakedEuler':list(leaf.rotation_euler),'closedEuler':[0,0,0]}]})
 if external:
  old=load(ROOT/'web/src/v2/household-room-data'/f'{key}.js')
  for p in ['householdStyle','entityId','geometryRevision']:
   if p in old:result[p]=old[p]
  result['externalSources']=external
 if degree not in [0,102]:result['degrees']=degree if'entry'in key else[degree]
 return result

def write(name,data):
 p=OUT/(name+'.js');p.write_text('// Generated by v2_house_textiles_gi73.py; original room fields retained.\nexport default '+json.dumps(data,separators=(',',':'))+';\n')
if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('--key',choices=['all','house_a',*[f'house_a-living-{i}'for i in range(3)],'house_a-entry-tea-34'],default='all');args=parser.parse_args()
 OUT.mkdir(exist_ok=True);keys=['house_a',*[f'house_a-living-{i}'for i in range(3)],'house_a-entry-tea-34']if args.key=='all'else[args.key]
 started=time.monotonic();report=[]
 for key in keys:
  states={}
  for degree in [102,0,30,60,90]:
   ext=assemble(key);states[degree]=state(key,degree,ext)
   if degree in [30,60,90]:write(key+'-'+str(degree),states[degree])
  opened=states[102];opened['closed']=states[0];write(key,opened)
  oldcontact=load(ROOT/'web/src/v2/legacy-room-data/house_a.js')['ROOM_CONTACT_DATA']if key=='house_a'else load(ROOT/'web/src/v2/household-room-data'/f'{key}.js')['contact']
  if oldcontact.get('reusePayload'):oldcontact=load(ROOT/'web/src/v2/legacy-room-data/house_a.js')['ROOM_CONTACT_DATA']
  report.append({'key':key,'contactPayloadEqual':opened['contact']['data']==oldcontact['data'],'seconds':time.monotonic()-started});print(json.dumps(report[-1]),flush=True)
 assert all(sha(Path(p))==h for p,h in protected.items())
 (ROOT/'tools/reports'/('house-textiles-gi73-'+args.key+'.json')).write_text(json.dumps({'derivedGeometry':DERIVED,'protectedSources':protected,'results':report},indent=2)+'\n')
